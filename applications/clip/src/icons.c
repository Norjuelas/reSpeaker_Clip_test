/* ========================================
 * Icon Drawing Functions
 * ======================================== */

/**
 * @brief Set pixel directly without mirror transformation
 * Internal helper function
 */
static inline void set_pixel_direct(uint8_t *buf, int x, int y)
{
	if (x < 0 || x >= OLED_WIDTH || y < 0 || y >= OLED_HEIGHT)
		return;
	buf[(y / 8) * OLED_WIDTH + x] |= (1 << (y % 8));
}

/**
 * @brief Draw bitmap icon to buffer
 *
 * Bitmap format: column-major order, 1 bit per pixel
 * Each column uses (height + 7) / 8 bytes
 */
void icon_draw_bitmap(uint8_t *buf, int x, int y,
                      const uint8_t *bitmap, uint8_t width, uint8_t height)
{
	if (!buf || !bitmap) {
		return;
	}

	/* Calculate bytes per row in the bitmap */
	uint8_t bytes_per_row = (width + 7) / 8;

	/* Draw each row */
	for (uint8_t row = 0; row < height; row++) {
		int draw_y = y + row;
		/* Skip if outside screen bounds */
		if (draw_y < 0 || draw_y >= OLED_HEIGHT) {
			continue;
		}
		for (uint8_t col = 0; col < width; col++) {
			int draw_x = x + col;
			/* Skip if outside screen bounds */
			if (draw_x < 0 || draw_x >= OLED_WIDTH) {
				continue;
			}
			/* Column-major: swap row/col for byte indexing */
			uint8_t byte_idx = col * bytes_per_row + (row / 8);
			uint8_t bit_idx = 7 - (row % 8);

			/* Check if pixel is set */
			if (bitmap[byte_idx] & (1 << bit_idx)) {
				/* Set pixel in frame buffer using direct pixel function */
				set_pixel_direct(buf, draw_x, draw_y);
			}
		}
	}
}

/**
 * @brief Get icon bitmap data by ID
 */
const uint8_t* icon_get_bitmap(icon_id_t id, uint8_t *width, uint8_t *height)
{
	if (width) {
		*width = ICON_WIDTH;
	}
	if (height) {
		*height = ICON_HEIGHT;
	}

	switch (id) {
	case ICON_WIFI_CONNECTED:
	case ICON_WIFI_TRANSFER:
		/* WiFi icon */
		return icon_wifi;

	case ICON_BATTERY_FULL:
		return icon_battery_low;

	case ICON_BATTERY_CHARGING:
		return icon_charge;

	case ICON_BATTERY_LOW:
		return icon_battery_low;

	case ICON_BLE_CONNECTED:
		return icon_ble;

	case ICON_BLE_TRANSFER:
		return icon_transfer;

	case ICON_PHONE:
		return icon_phone;

	case ICON_WIRED_CHARGING:
		return icon_wired_charging;

	case ICON_ARROW:
		return icon_arrow;

	case ICON_WIFI_CLIENT:
		return icon_wifi_client;

	case ICON_WIFI_UDP:
		return icon_wifi_udp;

	case ICON_WIRED_TRANSFER:
		return icon_wired_transfer;

	case ICON_LOW_BATTERY_DISPLAY:
		return icon_low_battery_display;

	case ICON_DISCONNECT_NOT_TRANSFORM:
		return icon_disconnect_not_transform;

	case ICON_OTA:
		return icon_ota;

	case ICON_POWER:
		return icon_power;

	case ICON_MIC_NORMAL:
	case ICON_MIC_ENHANCED:
	case ICON_MIC_MUTED:
	case ICON_USB_CONNECTED:
	case ICON_CONNECTED:
	case ICON_DISCONNECTED:
	default:
		return NULL;
	}
}
